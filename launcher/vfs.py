"""Writing the VFS manifest and deploying the loader.

The manifest is the entire contract between this launcher and the DLL that
runs inside the game (Files/Matchmaking/bros_vfs.c). It is regenerated from
scratch on every launch, so there is no install state to drift, no
uninstall step to get wrong, and no way for a stale entry to survive a
settings change.

What actually lands in the game folder:

    dinput8.dll        the loader (was already there for matchmaking)
    patch_ranked.txt   the matchmaking pool code (pre-existing)
    bros_vfs.log       a log, rewritten each launch
    patch_ranked.log   a log, pre-existing
    patch_ranked.log.1 the previous log, moved aside once it passes 4 MB

and nothing else. The manifest itself is deliberately kept OUT of the game
folder -- it lives in the repo and is pointed at with an environment
variable -- so that patch content never appears under the game directory at
all.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

MANIFEST_ENV = "BROS_VFS_MANIFEST"
MANIFEST_NAME = "bros_vfs_manifest.txt"
LOADER_NAME = "dinput8.dll"

# Files the patch is responsible for putting in the game folder. Used by
# uninstall() so "remove the patch" is an exact, enumerable operation
# instead of a guess.
GAME_FOLDER_ARTIFACTS = (
    LOADER_NAME,
    MANIFEST_NAME,
    "patch_ranked.txt",
    "patch_ranked.log",
    "patch_ranked.log.1",   # the previous log, moved aside by the loader at boot
    "bros_vfs.log",
)


def manifest_path(base_dir: Path) -> Path:
    """Where the manifest is written. Inside the repo, not the game."""
    return Path(base_dir) / "Runtime" / MANIFEST_NAME


def write_manifest(
    path: Path,
    game_root: Path,
    overlay,
    *,
    enum_merge: bool = True,
    log_level: int = 1,
    header_note: str = "",
) -> tuple:
    """Write the manifest the DLL reads. Returns (files_listed, new_files).

    Keys are normalised here -- lowercase, forward slashes -- and the DLL
    normalises incoming paths the same way. Doing it in one place means the
    two normalisers cannot drift apart in a way only one side notices.

    The trailing flag on each line is 1 when the stock game folder has no
    file at that path. Only those files need injecting into directory
    listings; a replacement is already listed by the real enumeration, and
    injecting it again would show the game the same name twice.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    game_root = Path(game_root)

    lines = ["BROSVFS1"]
    lines.append(f"# generated by the launcher -- rewritten on every launch, do not edit")
    if header_note:
        for note_line in header_note.splitlines():
            lines.append(f"# {note_line}")
    lines.append(f"root\t{game_root}")
    lines.append(f"opt\tenum_merge\t{1 if enum_merge else 0}")
    lines.append(f"opt\tlog_level\t{int(log_level)}")

    count = new_count = 0
    for rel in sorted(overlay.files):
        source, _label = overlay.files[rel]
        # One stat per file, reused for both the flag and the caller's summary.
        is_new = 0 if (game_root / rel).exists() else 1
        lines.append(f"file\t{rel.lower()}\t{source}\t{is_new}")
        count += 1
        new_count += is_new

    # newline="\n" so the DLL's line splitter sees exactly what it expects
    # regardless of the platform this launcher happens to run on.
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return count, new_count


def deploy_loader(base_dir: Path, game_root: Path) -> bool:
    """Put dinput8.dll in the game folder if it is missing or out of date.

    Returns True if the file was written. Compared by content rather than
    timestamp: a `git pull` rewrites mtimes on files whose bytes did not
    change, and copying a 190 KB DLL on every launch for no reason is the
    kind of thing that eventually races an antivirus scan.
    """
    src = Path(base_dir) / "Files" / "Matchmaking" / LOADER_NAME
    dst = Path(game_root) / LOADER_NAME
    if not src.is_file():
        raise FileNotFoundError(f"loader missing from the repo: {src}")

    if dst.is_file() and dst.stat().st_size == src.stat().st_size:
        if dst.read_bytes() == src.read_bytes():
            return False
    shutil.copy2(src, dst)
    return True


def remove_loader(game_root: Path) -> None:
    """Take the loader out, for a clean EasyAntiCheat/vanilla launch."""
    p = Path(game_root) / LOADER_NAME
    if p.exists():
        p.unlink()


def launch_env(base_dir: Path) -> dict:
    """Environment for the game process, pointing the DLL at the manifest."""
    env = dict(os.environ)
    env[MANIFEST_ENV] = str(manifest_path(base_dir))
    return env


def uninstall(game_root: Path) -> list:
    """Remove every file the patch puts in the game folder.

    This is the whole uninstall. Because the VFS never writes game content
    to disk, there is nothing else to undo -- which is the entire point of
    the exercise.
    """
    removed = []
    game_root = Path(game_root)
    for name in GAME_FOLDER_ARTIFACTS:
        p = game_root / name
        if p.exists():
            try:
                p.unlink()
                removed.append(name)
            except OSError:
                pass
    return removed
